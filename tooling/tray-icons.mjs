import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {execFileSync} from 'node:child_process';

export function buildTray({states,draw}) {
  const sizes=[16,20,24,32,48];
  const assets=[];
  for(const small of [false,true]) for(const state of states) for(const theme of ['light','dark']) {
    const variant=`${small?'small-':''}${state}-${theme}`;
    const entries=[];
    for(const size of sizes) {
      const extent=small?size*.75:size;
      const inset=Math.floor((size-extent)/2);
      const ink=theme==='dark'?'#fff':'#1b1b1b';
      const svg=`<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}" fill="${ink}"><g transform="translate(${inset} ${inset})">${draw(extent,state,ink)}</g></svg>`;
      const target=`src-tauri/icons/${variant}`;
      mkdirSync(target,{recursive:true});
      const source=`assets/tray-${variant}-${size}.svg`;
      writeFileSync(source,svg);
      execFileSync(process.execPath,['node_modules/@tauri-apps/cli/tauri.js','icon',source,'--output',target,'--png',String(size)],{stdio:'pipe'});
      const png=readFileSync(`${target}/${size}x${size}.png`);
      const entry=Buffer.alloc(16);
      entry[0]=size;entry[1]=size;entry.writeUInt16LE(1,4);entry.writeUInt16LE(32,6);entry.writeUInt32LE(png.length,8);
      entries.push({entry,png});
    }
    assets.push(`("${variant}",[${sizes.map(size=>`include_bytes!("../icons/${variant}/${size}x${size}.png").as_slice()`).join(',')}])`);
    if(!small) {
      const header=Buffer.alloc(6);header.writeUInt16LE(1,2);header.writeUInt16LE(entries.length,4);
      let offset=6+entries.length*16;
      for(const {entry,png} of entries){entry.writeUInt32LE(offset,12);offset+=png.length;}
      writeFileSync(`src-tauri/icons/${variant}.ico`,Buffer.concat([header,...entries.map(e=>e.entry),...entries.map(e=>e.png)]));
    }
  }
  writeFileSync('src-tauri/src/tray_assets.rs',`// Generated by the shared tray-icon pipeline.\nconst ARTWORK: linen_tray::Artwork = &[\n${assets.join(',\n')}\n];\n`);
}
